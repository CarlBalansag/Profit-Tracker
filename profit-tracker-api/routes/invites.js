const { createHash, randomBytes } = require('node:crypto');
const express = require('express');
const defaultPrisma = require('../prisma');

const hash = value => createHash('sha256').update(value).digest('hex');

function isAdmin(...emails) {
  const list = (process.env.ADMIN_EMAILS || '')
    .split(',')
    .map(s => s.trim().toLowerCase())
    .filter(Boolean);
  return emails.some(e => e && typeof e === 'string' && list.includes(e.trim().toLowerCase()));
}

function createInvitesRouter({ prisma = defaultPrisma } = {}) {
  const router = express.Router();

  const isAuthenticated = (req, res, next) => {
    if (req.user) return next();
    res.status(401).json({ error: 'Sign-in required.' });
  };

  const requireAdmin = (req, res, next) => {
    if (req.user && isAdmin(req.user.email, req.firebaseIdentity?.email)) return next();
    res.status(403).json({ error: 'Admin access required.' });
  };

  // GET /api/invites — list all invites generated by this admin
  router.get('/', isAuthenticated, requireAdmin, async (req, res, next) => {
    try {
      const invites = await prisma.invite.findMany({
        where: { created_by: req.user.id },
        orderBy: { created_at: 'desc' },
        select: {
          id: true,
          expires_at: true,
          consumed: true,
          used_by: true,
          created_at: true,
        },
      });
      const now = new Date();
      const formatted = invites.map(inv => ({
        id: inv.id,
        expires_at: inv.expires_at,
        consumed: inv.consumed,
        used_by: inv.used_by,
        created_at: inv.created_at,
        status: inv.consumed ? 'used' : (inv.expires_at <= now ? 'expired' : 'active'),
      }));
      res.json(formatted);
    } catch (err) {
      next(err);
    }
  });

  // POST /api/invites — create a 3-day single-use invite link
  router.post('/', isAuthenticated, requireAdmin, async (req, res, next) => {
    try {
      const token = randomBytes(24).toString('hex');
      const token_hash = hash(token);
      // 3 days expiration
      const expires_at = new Date(Date.now() + 3 * 24 * 60 * 60 * 1000);
      const invite = await prisma.invite.create({
        data: {
          token_hash,
          created_by: req.user.id,
          expires_at,
        },
        select: {
          id: true,
          expires_at: true,
          consumed: true,
          created_at: true,
        },
      });
      res.status(201).json({
        ...invite,
        token,
        status: 'active',
      });
    } catch (err) {
      next(err);
    }
  });

  // DELETE /api/invites/:id — delete/revoke an invite
  router.delete('/:id', isAuthenticated, requireAdmin, async (req, res, next) => {
    try {
      const result = await prisma.invite.deleteMany({
        where: { id: req.params.id, created_by: req.user.id },
      });
      if (result.count === 0) {
        return res.status(404).json({ error: 'Invite not found.' });
      }
      res.json({ success: true });
    } catch (err) {
      next(err);
    }
  });

  // GET /api/invites/validate — public validation endpoint
  router.get('/validate', async (req, res, next) => {
    try {
      const token = req.query.token;
      if (!token || typeof token !== 'string' || token.length < 16 || token.length > 128) {
        return res.status(400).json({ valid: false, reason: 'invalid_token' });
      }
      const token_hash = hash(token);
      const invite = await prisma.invite.findUnique({
        where: { token_hash },
        select: {
          id: true,
          expires_at: true,
          consumed: true,
        },
      });
      if (!invite) {
        return res.status(404).json({ valid: false, reason: 'not_found' });
      }
      if (invite.consumed) {
        return res.status(410).json({ valid: false, reason: 'consumed' });
      }
      if (invite.expires_at <= new Date()) {
        return res.status(410).json({ valid: false, reason: 'expired' });
      }
      res.json({ valid: true, expires_at: invite.expires_at });
    } catch (err) {
      next(err);
    }
  });

  return router;
}

const defaultRouter = createInvitesRouter();

module.exports = {
  router: defaultRouter,
  createInvitesRouter,
  isAdmin,
  hash,
};
